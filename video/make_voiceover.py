"""Generate the UNWRAP voice-over with Microsoft neural voices (edge-tts, needs internet).

Usage:  python make_voiceover.py [voice] [rate]
        python make_voiceover.py en-US-AndrewNeural -4%
Other voices to try: en-US-GuyNeural, en-GB-RyanNeural, en-US-AriaNeural, en-GB-SoniaNeural.

Reads the narration from UNWRAP_video.html (the SCENES list), asks the voice for audio plus
word-by-word timestamps, and writes voiceover.js (audio embedded as base64) which the video page loads.
"""
import asyncio, base64, json, re, sys, pathlib
import edge_tts

HERE = pathlib.Path(__file__).parent
VOICE = sys.argv[1] if len(sys.argv) > 1 else "en-US-AndrewNeural"
RATE = sys.argv[2] if len(sys.argv) > 2 else "-4%"

html = (HERE / "UNWRAP_video.html").read_text(encoding="utf8")
scenes = re.findall(r"\{id:'(s\d)',\s*name:'[^']*',\s*vo:`(.*?)`\}", html, flags=re.S)
if not scenes:
    sys.exit("could not find the narration in UNWRAP_video.html")

async def synth(text):
    com = edge_tts.Communicate(text, VOICE, rate=RATE, boundary="WordBoundary")
    audio, words = bytearray(), []
    async for ch in com.stream():
        if ch["type"] == "audio":
            audio += ch["data"]
        elif ch["type"] == "WordBoundary":
            words.append([round(ch["offset"] / 1e7, 3), round(ch["duration"] / 1e7, 3), ch["text"]])
    return bytes(audio), words

async def main():
    out = {}
    (HERE / "audio").mkdir(exist_ok=True)
    for sid, vo in scenes:
        text = re.sub(r"\[\[\w+\]\]", "", vo)
        text = re.sub(r"\s+", " ", text).strip()
        audio, words = await synth(text)
        (HERE / "audio" / f"{sid}.mp3").write_bytes(audio)
        end = words[-1][0] + words[-1][1] if words else 0
        out[sid] = {"a": base64.b64encode(audio).decode(), "words": words, "dur": round(end, 2)}
        print(sid, f"{len(words)} words, ~{end:.1f}s, {len(audio)//1024} KB")
    (HERE / "voiceover.js").write_text(
        "/* generated by make_voiceover.py - voice: %s, rate: %s */\nwindow.VO_DATA=%s;\n" % (VOICE, RATE, json.dumps(out)),
        encoding="utf8")
    print("wrote voiceover.js with voice", VOICE)

asyncio.run(main())
